/**
 * Основной шаблон для запросов к Perplexity
 * Используется как для fast, так и для deep/pro поиска
 *
 * Требует от Perplexity:
 * - Ответ в виде псевдотаблицы для Telegram (MarkdownV2)
 * - Структура: Год | Значение | Источник
 * - Только доверенные российские источники
 */
export const PERPLEXITY_QUERY_TEMPLATE = `
Сформируй ответ строго в виде псевдотаблицы для Telegram, без пояснений до и после.
Требования к формату:
Используй обычный текст с разделителями | , как в Markdown-таблицах.
Первая строка — заголовки колонок: Год | Значение | Источник | Релевантность.
В каждой строке данных:
Год (например, 2025).
Значение (число, без округления до миллионов/тысяч).
Источник в виде кликабельной Markdown-ссылки: [НАЗВАНИЕ ИЗДАНИЯ](URL) с учетом MarkdownV2 Telegram (нужен parse_mode = "MarkdownV2").
Не добавляй текст вне таблицы.
НЕ добавляй список источников в конце (типа [1], [2], [3]...).
Экранируй спецсимволы для MarkdownV2 при необходимости.

Используй только доверенные источники - другие источники исключай:
Российская газета, РБК, ТАСС, Интерфакс, РИА Новости, Коммерсантъ, Ведомости, Известия, Комсомольская правда, Московский комсомолец, Аргументы и факты, Парламентская газета, сайты Министерств, Правительства РФ, Росстат, научные статьи

Если нет информации из доверенных источников - верни ответ "информация не найдена".
Если релевантная информация не найдена - верни ответ "информация не найдена".

ВАЖНО - не путай значения преподавателей, работников, обучающихся.

Пример ответа:

Год | Значение | Источник | Релевантность
2024 | 18000000 | ТАСС | 90%
2025 | 18000000 | Российская газета | 100%
`.trim();
