/**
 * Создать пользовательское сообщение для LLM
 * @param query - запрос пользователя
 * @returns сообщение для LLM
 */
export function createClarificationMessage(query: string): string {
  return `Запрос: "${query}"

Проанализируй запрос, определи уровень неопределенности и сгенерируй 0-7 вариантов интерпретации.
Попытайся УГАДАТЬ, что реально хочет узнать пользователь.
Ответ СТРОГО JSON с полями: suggestions (массив с id, label, description), reasoning, warning (опционально).`;
}
